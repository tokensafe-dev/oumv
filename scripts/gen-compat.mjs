/**
 * Generates compatibility.json (spec §11): the one-table answer to "which
 * standard release ships which wire version, document revision and fixture
 * set". CI runs `--check` so the checked-in file can never drift from the
 * package versions in the repo.
 *
 * Usage: node scripts/gen-compat.mjs [--check]
 */
