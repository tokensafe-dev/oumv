const [current, ...previous] = REVISIONS;
const currentRow = {
  ...current,
  rootPackageVersion: rootPkg.version,
  fixtureVersionOnDisk: fixtures.fixtureVersion,
  protocolVersionOnDisk: fixtures.protocolVersion,
};

const generated = {
  $comment: 'Generated by scripts/gen-compat.mjs — do not edit by hand. CI checks this file against the package versions on disk (spec §11).',
  current: currentRow,
  previous,
};

if (process.argv.includes('--check')) {
  const onDisk = JSON.parse(readFileSync('compatibility.json', 'utf-8'));
  const stale =
    JSON.stringify(onDisk.current) !== JSON.stringify(generated.current) ||
    JSON.stringify(onDisk.previous ?? []) !== JSON.stringify(generated.previous);
  if (stale) {
    console.error('compatibility.json is stale: run `node scripts/gen-compat.mjs`');
    process.exit(1);
  }
  console.log('compatibility.json is up to date.');
} else {
  writeFileSync(join(root, 'compatibility.json'), JSON.stringify(generated, null, 2) + '\n');
  console.log(`Wrote compatibility.json (current ${currentRow.release}, wire ${currentRow.wireProtocolVersion}, fixtures ${currentRow.fixtureVersion}).`);
}
